"""Collect the JSON schema that CorelDRAW 2019 write (to filter key unusual of newer version 2024).

  python json2019.py --survey                  # in statistics list
  python json2019.py --emit <file.cs>          # generate the C# table Schema2019

Source JSON: styles/document.cdss, object number style 0xC9 in loda, the block JSON in txsm.
Read only files has vrsn 2100 (CorelDRAW 2019).
"""
import collections
import glob
import json
import os
import struct
import sys
import zipfile

sys.path.insert(0, os.path.dirname(__file__))
from cdrtree import load  # noqa: E402
from lodadiff import parse_loda  # noqa: E402

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SOURCES = [
    "samples/gen/*_21.cdr", "out/real/*_21.cdr", "samples/*_21.cdr",
    "D:/DuAnClaude/C_Auto/*.cdr", "D:/tesst/*/*.cdr",
]
# Objects whose child keys are user/content-defined (style names, level names…): do not filter child keys directly.
DYNAMIC = {"style", "color styles", "levels", "fom data", "export", "symmetry"}


def txsm_blobs(d):
    i = 4
    while i < len(d) - 1:
        if d[i:i + 1] == b"{":
            ln = struct.unpack_from("<I", d, i - 4)[0]
            if 2 <= ln <= len(d) - i and d[i + ln - 1:i + ln] == b"}":
                try:
                    yield json.loads(d[i:i + ln])
                    i += ln
                    continue
                except ValueError:
                    pass
        i += 1


def documents(path):
    z = zipfile.ZipFile(path)
    leaves = load(path)
    vrsn = next(struct.unpack_from("<H", d)[0] for p, c, d in leaves if c == "vrsn")
    if vrsn != 2100:
        return
    if "styles/document.cdss" in z.namelist():
        yield "cdss", json.loads(z.read("styles/document.cdss"))
    for p, c, d in leaves:
        if c == "loda":
            try:
                _, args = parse_loda(d)
            except struct.error:
                continue
            a = args.get(0xC9)
            if a and len(a) >= 8 and struct.unpack_from("<I", a)[0] == 1:
                yield "loda", json.loads(a[8:])
        elif c == "txsm":
            for j in txsm_blobs(d):
                yield "txsm", j


def collect():
    schema = collections.defaultdict(set)  # name object → key con
    files = 0
    for pat in SOURCES:
        for f in glob.glob(pat if os.path.isabs(pat) else os.path.join(ROOT, pat)):
            got = False
            for kind, doc in documents(f):
                got = True
                walk(doc, "<root>", schema)
            files += got
    return schema, files


def walk(node, name, schema):
    if isinstance(node, dict):
        if name not in DYNAMIC:
            schema[name].update(node.keys())
        for k, v in node.items():
            # Child of a dynamic object: arbitrary names → treat as "<item>".
            walk(v, "<item>" if name in DYNAMIC else k, schema)
    elif isinstance(node, list):
        for v in node:
            walk(v, name, schema)


if __name__ == "__main__":
    schema, files = collect()
    if "--emit" in sys.argv:
        out = sys.argv[sys.argv.index("--emit") + 1]
        lines = [
            "// <auto-generated> by tools/analysis/json2019.py from CorelDRAW 2019 files — do not edit manually.",
            "namespace CConvert.Core;",
            "",
            "/// <summary>JSON keys written by CorelDRAW 2019, grouped by containing object name (\"<root>\" = source, \"<item>\" = child of a dynamic object).</summary>",
            "internal static class Schema2019",
            "{",
            "    public static readonly HashSet<string> Dynamic = [" + ", ".join(f'"{n}"' for n in sorted(DYNAMIC)) + "];",
            "",
            "    public static readonly Dictionary<string, HashSet<string>> Keys = new()",
            "    {",
        ]
        for name in sorted(schema):
            keys = ", ".join(json.dumps(k, ensure_ascii=False) for k in sorted(schema[name]))
            lines.append(f"        [{json.dumps(name, ensure_ascii=False)}] = [{keys}],")
        lines += ["    };", "}", ""]
        open(out, "w", encoding="utf-8").write("\n".join(lines))
        print(f"written {out}: {len(schema)} object, from {files} file")
    else:
        print(f"{files} file 2019, {len(schema)} object types")
        for name in sorted(schema, key=lambda n: -len(schema[n]))[:40]:
            print(f"  {name:<28} {len(schema[name]):>4} key  {sorted(schema[name])[:8]}")
